export interface ScenarioUser {
  readonly id: number;
  readonly login: string;
  readonly name: string;
  readonly email: string;
}

function generateUsers(count: number): ScenarioUser[] {
  const rng = scenarioRng('users');
  const used = new Set<string>();
  const users: ScenarioUser[] = [];
  for (let i = 0; i < count; i += 1) {
    const first = rng.pick(FIRST_NAMES);
    const last = rng.pick(LAST_NAMES);
    const base = `${first}${last}`.replace(/[^a-z0-9-]/g, '');
    let login = base;
    let suffix = 2;
    while (used.has(login)) {
      login = `${base}-${suffix}`;
      suffix += 1;
    }
    used.add(login);
    users.push(Object.freeze({ id: 1000 + i, login, name: `${first} ${last}`, email: `${login}@example.invalid` }));
  }
  return users;
}

/** The suite's twelve users; index 0 is the token's owner (the viewer). */
export const USERS: readonly ScenarioUser[] = Object.freeze(generateUsers(12));

/** The account every authenticated request acts as: the scenario's viewer. */
export const VIEWER: ScenarioUser = USERS[0] as ScenarioUser;

