/** Deterministic label colours, GitHub-flavoured, derived from the label name alone. */
export function labelColor(name: string): string {
  let hash = 0;
  for (let i = 0; i < name.length; i += 1) hash = (hash * 31 + name.charCodeAt(i)) >>> 0;
  const palette = ['d73a4a', '0075ca', '008672', 'e4e669', 'a2eeef', '7057ff', 'd876e3', 'ffffff'];
  return palette[hash % palette.length] as string;
}
